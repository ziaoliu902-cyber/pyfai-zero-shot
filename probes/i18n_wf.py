# 从右到左书写的语种（gui_workflow 据此设置布局方向）
RTL_LANGS = {"ar"}

_CUR_LANG = "zh"


def _default_lang():
    """首次启动：按系统区域设置挑语言；无匹配回退 zh。"""
    name = QLocale.system().name()  # e.g. "zh_CN" / "en_US" / "ar_EG"
    base = name.split("_")[0] if name else ""
    if name in _TABLE:
        return name
    if base == "zh":
        # 区分大陆/台湾用语习惯
        return "zh_TW" if name in ("zh_TW", "zh_HK", "zh_MO") else "zh"
    return base if base in _TABLE else "zh"


def get_lang():
    return _CUR_LANG


def set_lang(code, persist=True):
    """切换当前语言；persist=True 时写入 QSettings 永久记忆。"""
    global _CUR_LANG
    assert code in _TABLE, "unknown lang code: %r" % code
    _CUR_LANG = code
    if persist:
        QSettings("pyfai", "gui_workflow").setValue("lang", code)


def init_lang():
    """启动时调用一次：读取记忆或按系统区域初始化。"""
    saved = QSettings("pyfai", "gui_workflow").value("lang", "", type=str)
    global _CUR_LANG
    if saved in _TABLE:
        _CUR_LANG = saved
    else:
        _CUR_LANG = _default_lang()
    return _CUR_LANG


def tr(key, **kw):
    """取当前语言的模板串；缺键回退 zh，再缺回退键名。带 kw 时做 format。"""
    d = _TABLE.get(_CUR_LANG, _TABLE["zh"])
    s = d.get(key) or _TABLE["zh"].get(key) or key
    return s.format(**kw) if kw else s


def tr_for(code, key, **kw):
    """按指定语言取词，不改变当前语言（供 matplotlib 渲染层等定向取词用）。"""
    d = _TABLE.get(code) or _TABLE["zh"]
    s = d.get(key) or _TABLE["zh"].get(key) or key
    return s.format(**kw) if kw else s


def is_rtl():
    return _CUR_LANG in RTL_LANGS


def localize_conf(conf, has_d_ref=False, lang=None):
    """confidence_map.evaluate_confidence 输出的中文 tier/badge/rationale/recommendation
    的显示层本地化。分支判定与 confidence_map 严格同构（该产品调用路径 max_dev=None，
    conf 自带 m/ps/az_cov/cv_ratio；has_d_ref 由调用方从求解结果补传）。
    lang=None 时用当前语言（GUI 默认）；指定 lang 时按该语言定向取词、
    不动全局状态（matplotlib 渲染层用，如 ar 导出回退 en 的场合）。
    返回 dict(tier, badge, rationale, recommendation, raw_tier)。
    """
    try:
        m = int(conf.get("m", 0) or 0)
    except (TypeError, ValueError):
        m = 0
    try:
        ps = float(conf.get("ps", 0.0) or 0.0)
    except (TypeError, ValueError):
        ps = 0.0
    try:
        az = float(conf.get("az_cov", 1.0) if conf.get("az_cov", 1.0) is not None else 1.0)
    except (TypeError, ValueError):
        az = 1.0
    cv = conf.get("cv_ratio")
    cv_finite = cv is not None and cv == cv and cv not in (float("inf"), float("-inf"))

    if az < 0.40:
        b, r, k = "cb_arc", "cr_arc", "ck_arc"
    elif m == 3 and ps >= 0.60 and has_d_ref:
        b, r, k = "cb_hi3", "cr_hi3", "ck_hi3"
    elif m == 3 and ps >= 0.60:
        b, r, k = "cb_md3", "cr_md3", "ck_md3"
    elif m < 4:
        b, r, k = "cb_low_m", "cr_low_m", "ck_low_m"
    elif ps < 0.20:
        b, r, k = "cb_low_ps", "cr_low_ps", "ck_low_ps"
    elif cv_finite and m <= 5 and cv > 2.5:
        b, r, k = "cb_low_cv", "cr_low_cv", "ck_low_cv"
    elif ps >= 0.40:
        b, r, k = "cb_hi", "cr_hi", "ck_hi"
    else:
        b, r, k = "cb_md", "cr_md", "ck_md"

    raw_tier = str(conf.get("tier", "MEDIUM"))
    kw = dict(m=m, ps="%.3f" % ps, az="%.0f%%" % (az * 100),
              cv="%.2f" % cv if cv_finite else "-")
    if lang is None:
        _t, _tbl = tr, _TABLE.get(_CUR_LANG, _TABLE["zh"])
    else:
        _t = lambda k, **w: tr_for(lang, k, **w)  # noqa: E731
        _tbl = _TABLE.get(lang) or _TABLE["zh"]
    return dict(
        tier=_t("tier_" + raw_tier) if ("tier_" + raw_tier) in _tbl else raw_tier,
        badge=_t(b, **kw),
        rationale=_t(r, **kw),
        recommendation=_t(k, **kw),
        raw_tier=raw_tier,
    )

