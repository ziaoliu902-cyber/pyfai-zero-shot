# 谐波（层状）标样：d_n = d_1/n 的整数阶序列。只出 3–4 条环时同一张图在
# D×k（k 整数）下同样自洽（rms 可 <0.2px），D 绝对值不可判——GUI 由此列候选
# 距离/按「近似距离」吸附（2026-11-06 泛化：新增层状相只需加进这个集合）。
# LaB6 严格说是立方混合序列，但其 (n00) 子列谐波 + 高阶弱化，低环数时同样
# 存在整数倍歧义，保守并入（与 2026-11-06 之前的行为一致）。
HARMONIC_PHASES = frozenset({"AgBh", "LaB6", "AgSt"})

PHASE_NAMES = list(PHASES.keys())


def phase_qs(name: str) -> np.ndarray:
    """返回该相所有衍射峰的 q（Å⁻¹），升序。"""
    d, _, _ = PHASES[name]
    return 2.0 * np.pi / d


def phase_qi(name: str):
    """返回 (q, I_rel)。"""
    d, I, _ = PHASES[name]
    return 2.0 * np.pi / d, I / 100.0
